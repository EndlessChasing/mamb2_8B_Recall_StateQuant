def controlled_inputs(special,np,torch):
    length=65 if special=='dyadic' else 5
    order=np.stack([np.roll(np.arange(127,-1,-1),13*g) for g in range(2)]).astype(np.uint8)
    pattern8=np.array([-127,-126.5,-64,-1.5,-.5,0,.5,1.5,64,126.5,127],np.float32)
    pattern4=np.array([-7,-6.5,-4,-1.5,-.5,0,.5,1.5,4,6.5,7],np.float32)
    wanted=np.concatenate((np.resize(pattern8,32),np.resize(pattern4,32),(np.arange(64)%5-2).astype(np.float32)))
    if special=='rounded_scales':wanted[0]=127.0625;wanted[32]=7.00390625
    if special in ('underflow','subnormal','wide_safe'):
        wanted=np.sign(wanted)*np.float32({'underflow':2**-19,'subnormal':2**-11,'wide_safe':4096.}[special])
    if special=='zero':wanted.fill(0)
    x=np.empty((2,length,4,19),np.float16);B=np.empty((2,length,2,128),np.float16);C=np.zeros_like(B)
    for b in range(2):
        for h in range(4):
            exponents=(b+h+np.arange(19))%3-5
            x[b,:,h,:]=((-1.)**(b+h+np.arange(19))*2.**exponents)[None,:]
        for t in range(length):
            for g in range(2):
                B[b,t,g,order[g]]=(wanted*np.float32((1,1,-1,-1)[t%4])/np.float32(32)).astype(np.float16)
                C[b,t,g,order[g,(0,31,32,63,64,127)[t%6]]]=(-1.)**(b+g)*2**-8
    if special in ('underflow','subnormal'):x.fill(2**-5)
    arrays=[x,np.zeros((2,length,4),np.float16),np.zeros(4,np.float32),B,C,
        np.zeros(4,np.float16),np.full(4,32,np.float32)]
    return [torch.from_numpy(v) for v in arrays],torch.from_numpy(order)


