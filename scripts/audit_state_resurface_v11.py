def probe_evidence(path,report,binding,train,torch,tensors,final_checkpoint):
    item=report['probe_evidence'];p=path.parent/item['file']
    need(Path(item['file']).name==item['file'] and sha(p)==item['sha256'] and p.stat().st_size==item['bytes'],
         'Raw parity evidence file differs')
    proof=torch.load(p,map_location='cpu',weights_only=True)
    need(proof['format']=='MAMBA2_STATE_RESURFACE_V11_TRAIN_PROOF_V1' and proof['binding']==binding,
         'Raw parity evidence binding differs')
    for phase,field in (('initialization','initialization_check'),('export','deployed_export_check')):
        entries=proof[phase];receipts=report[field]['probes']
        need(set(entries)=={'128','512'} and [r['probe_tokens'] for r in receipts]==[128,512], 'Both parity lengths required')
        for length,row in zip((128,512),receipts):
            entry=entries[str(length)];tokens=entry['token_ids'];a=entry['packed_hidden'];b=entry['training_hidden']
            need(tokens.dtype==torch.int64 and torch.equal(tokens,train[0,:length][None]),'Probe must use fixed TRAIN prefix')
            need(a.dtype==b.dtype==torch.float16 and tuple(a.shape)==tuple(b.shape)==(1,length,4096)
                 and bool(torch.isfinite(a).all()) and torch.equal(a,b),'Raw packed/training hidden tensors differ')
            need(row['probe_token_sha256']==tokhash(tokens.flatten().tolist())
                 and row['packed_hidden_sha256']==tensor_sha(a) and row['training_hidden_sha256']==tensor_sha(b)
                 and row['packed_training_forward_bitwise_equal'] is True and row['packed_probe_finite'] is True,
                 'Raw parity hash/receipt differs')
            cache_check(row['cache'],'old_sq',length)
        need(report[field]['cache']==receipts[0]['cache'],'Legacy128 cache alias differs')
    masters=proof['masters'];need(set(masters)==set(shapes()),'Raw final master inventory differs')
    for name,shape in shapes().items():
        value=masters[name]
        need(value.dtype==torch.float32 and tuple(value.shape)==shape and bool(torch.isfinite(value).all())
             and torch.equal(value.half(),tensors[name]),'Actual final FP32-to-FP16 export differs')
        if final_checkpoint is not None:
            need(torch.equal(value,final_checkpoint['masters'][name]),'Probe/master proof differs from final checkpoint')
    need(any(bool((v!=0).any()) for n,v in tensors.items() if n.endswith('.V_read')),
         'Nonzero trained export probe required')
    return dict(file_sha256=item['sha256'],lengths=[128,512],raw_initialization_and_export_exact=True,
        raw_master_casts_exact=True,nonzero_export=True)


