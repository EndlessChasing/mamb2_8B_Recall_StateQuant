def controlled_recompute(inputs,table,packed,output,np,torch):
    x,raw,A,B,C,D,bias=[v.numpy().astype(np.float32) for v in inputs]
    order=table.numpy().astype(np.int64);batch,length,heads,dim=x.shape
    previous=np.zeros((batch,heads,dim,128),np.float32);results=[]
    for t in range(length):
        # All six fixed controlled fixtures have dt32/decay1 exactly.
        need(not raw[:,t].any() and not A.any() and np.all(bias==32),'Controlled scalar fixture changed')
        group=np.arange(heads)//(heads//len(order));perm=order[group]
        b=np.take_along_axis(B[:,t,group,:],perm[None],-1)
        c=np.take_along_axis(C[:,t,group,:],perm[None],-1)
        updated=(previous.astype(np.float64)+(b*np.float32(32))[:,:,None,:].astype(np.float32)*x[:,t,...,None]).astype(np.float32)
        product=updated*c[:,:,None,:]
        y=product[...,:32].sum(-1,dtype=np.float32)+product[...,32:64].sum(-1,dtype=np.float32)
        y+=product[...,64:].sum(-1,dtype=np.float32)+x[:,t]*D[None,:,None]
        results.append(y.astype(np.float16))
        expected=v10.quantize_np(updated,LAYOUT,np)
        need(all(np.array_equal(packed[t][k].numpy().view(np.uint8),v.view(np.uint8)) for k,v in expected.items()),
             'Independent controlled integer/scale/packing recurrence differs')
        previous=v10.decode_np(expected,LAYOUT,np)
    wanted=torch.from_numpy(np.stack(results,1))
    need(output.dtype==torch.float16 and torch.equal(wanted,output),'Independent controlled readout differs')


def independent_ste(inputs,table,carries,gy,torch):
    """Rebuild a separate CPU autograd graph from raw input and decoded bytes.

    It uses exact recorded numerical carries with a retained identity tangent;
    neither the GPU backward nor the checker's serialized reference is called.
    """
    leaves=[v.float().detach().requires_grad_(i in (0,1,3,4)) for i,v in enumerate(inputs)]
    x,raw,A,B,C,D,bias=leaves;batch,length,heads,dim=x.shape
    group=torch.arange(heads)//(heads//table.shape[0]);indices=table.long()[group]
    prev=torch.zeros((batch,heads,dim,128),dtype=torch.float32);outputs=[]
    for t in range(length):
        delta_input=raw[:,t]+bias
        # Recreate the declared elementary softplus expression without
        # importing the checker oracle, backward kernel or quantizer.
        delta=torch.where(delta_input<=20,torch.log(torch.exp(delta_input)+1),delta_input)
        decay=torch.exp(delta*A)
        bv=torch.gather(torch.index_select(B[:,t],1,group),2,indices[None].expand(batch,-1,-1))
        cv=torch.gather(torch.index_select(C[:,t],1,group),2,indices[None].expand(batch,-1,-1))
        addition=(bv*delta[...,None])[:,:,None,:]*x[:,t,...,None]
        state=(prev.to(torch.float64)*decay[...,None,None].to(torch.float64)+addition.to(torch.float64)).float()
        product=state*cv[:,:,None,:]
        y=product[...,:32].sum(-1)+product[...,32:64].sum(-1)
        y=y+(product[...,64:].sum(-1).double()+x[:,t].double()*D.double()[None,:,None]).float()
        outputs.append(y.half())
        retained=state[...,:64]
        prev=torch.cat((carries[t][...,:64]+(retained-retained.detach()),torch.zeros_like(state[...,64:])),dim=-1)
    out=torch.stack(outputs,1)
    return torch.autograd.grad(out,[leaves[i] for i in (0,1,3,4)],gy)


def gradient_facts(actual,expected,atol,rtol,torch):
    need(actual.dtype==torch.float16 and actual.shape==expected.shape and bool(torch.isfinite(actual).all())
         and bool(torch.isfinite(expected).all()),'Gradient dtype/shape/finiteness differs')
    a=actual.float();b=expected.half().float();error=(a-b).abs();bound=atol+rtol*b.abs()
    need(bool((error<=bound).all()),'Declared elementwise STE/replay gradient bound exceeded')
    return dict(max_absolute_error=float(error.max()),max_bound_ratio=float((error/bound).max()),
        relative_rms_error=float(error.square().mean().sqrt()/b.square().mean().sqrt().clamp_min(1e-12)),atol=atol,rtol=rtol)


