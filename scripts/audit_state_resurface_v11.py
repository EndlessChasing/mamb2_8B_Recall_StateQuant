def prediction_kind(row):
    prediction=row['prediction'];removed=row['condition']=='target_removed'
    if prediction==row['answer']:return 'removed_target_match' if removed else 'correct_target'
    if prediction is None:return 'unparseable'
    if any(int(prediction)==value for _,value in row['records']):
        return 'other_present_value' if removed else 'wrong_present_value'
    return 'not_present_value'


def group_summary(rows):
    categories={}
